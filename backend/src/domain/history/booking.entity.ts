import { Column, Entity, Index, JoinColumn, ManyToOne, Unique } from 'typeorm';
import { Company } from '../../modules/companies/entities/company.entity';
import { CompanyMembership } from '../../modules/company-memberships/entities/company-membership.entity';
import { bigintAsNumber, CompanyRef, IdPk, IdRef, UserRef, Utc, UtcNow } from '../columns';
import { Lead } from '../core/lead.entity';
import { Service } from '../core/service.entity';
import { BOOKING_STATUSES } from '../vocabulary';

/**
 * An appointment taken for a lead. A lead has at most ONE live (scheduled) booking: the original enforced it in code
 * and the database now does too, through a generated column that is the lead id while the booking is scheduled
 * and NULL otherwise, under a unique index (NULLs never collide).
 */
@Entity('bookings')
@Unique('UQ_bookings_company_id_id', ['company_id', 'id'])
@Index('UQ_bookings_one_live_per_lead', ['company_id', 'live_lead_id'], { unique: true })
@Index('IDX_bookings_reminder_owner', ['company_id', 'reminder_owner_user_id', 'scheduled_for'])
@Index('IDX_bookings_lead', ['company_id', 'lead_id'])
export class Booking {
  @IdPk()
  id: number;

  @CompanyRef()
  company_id: string;

  @ManyToOne(() => Company, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'company_id', foreignKeyConstraintName: 'FK_bookings_company' })
  company: Company;

  @IdRef('lead_id')
  lead_id: number;

  @ManyToOne(() => Lead, { onDelete: 'RESTRICT' })
  @JoinColumn([
    { name: 'company_id', referencedColumnName: 'company_id', foreignKeyConstraintName: 'FK_bookings_lead' },
    { name: 'lead_id', referencedColumnName: 'id' },
  ])
  lead: Lead;

  @UserRef('booked_by_user_id')
  booked_by_user_id: string;

  @ManyToOne(() => CompanyMembership, { onDelete: 'RESTRICT' })
  @JoinColumn([
    { name: 'company_id', referencedColumnName: 'company_id', foreignKeyConstraintName: 'FK_bookings_booked_by' },
    { name: 'booked_by_user_id', referencedColumnName: 'user_id' },
  ])
  booked_by: CompanyMembership;

  @IdRef('service_id', true)
  service_id: number | null;

  @ManyToOne(() => Service, { onDelete: 'RESTRICT', nullable: true })
  @JoinColumn([
    { name: 'company_id', referencedColumnName: 'company_id', foreignKeyConstraintName: 'FK_bookings_service' },
    { name: 'service_id', referencedColumnName: 'id' },
  ])
  service: Service | null;

  @Utc('contacted_at')
  contacted_at: Date;

  @Utc('scheduled_for')
  scheduled_for: Date;

  @UserRef('reminder_owner_user_id')
  reminder_owner_user_id: string;

  @ManyToOne(() => CompanyMembership, { onDelete: 'RESTRICT' })
  @JoinColumn([
    { name: 'company_id', referencedColumnName: 'company_id', foreignKeyConstraintName: 'FK_bookings_reminder_owner' },
    { name: 'reminder_owner_user_id', referencedColumnName: 'user_id' },
  ])
  reminder_owner: CompanyMembership;

  @Utc('reminder_call_at', true)
  reminder_call_at: Date | null;

  @Column({ type: 'varchar', length: 30, nullable: true })
  reminder_outcome: string | null;

  @Column({ type: 'enum', enum: BOOKING_STATUSES, default: 'scheduled' })
  status: (typeof BOOKING_STATUSES)[number];

  @Column({ type: 'text', nullable: true })
  notes: string | null;

  @UtcNow('created_at')
  created_at: Date;

  @Column({ type: 'varchar', length: 255, nullable: true })
  case_name: string | null;

  @Utc('reminder_message_at', true)
  reminder_message_at: Date | null;

  @Column({ type: 'int', unsigned: true, default: 0 })
  reminder_no_answer_count: number;

  @Utc('reminder_first_no_answer_at', true)
  reminder_first_no_answer_at: Date | null;

  /** Generated by MySQL, never written by the application: the lead id while `status = 'scheduled'`, else NULL. */
  @Column({
    name: 'live_lead_id',
    type: 'bigint',
    unsigned: true,
    nullable: true,
    insert: false,
    update: false,
    asExpression: "CASE WHEN `status` = 'scheduled' THEN `lead_id` ELSE NULL END",
    generatedType: 'STORED',
    transformer: bigintAsNumber,
  })
  live_lead_id: number | null;
}
