import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  OneToMany,
  ManyToOne,
  JoinColumn,
  Index,
  BeforeInsert,
  BeforeUpdate,
} from 'typeorm';
import { toCanonicalPhone } from '../../../common/phone/phone';
import { CompanyMembership } from '../../company-memberships/entities/company-membership.entity';

export enum UserStatus {
  PENDING = 'pending',
  ACTIVE = 'active',
  INACTIVE = 'inactive',
  SUSPENDED = 'suspended',
}

@Entity('users')
export class User {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Column({ length: 255 })
  name: string;

  @Column({ unique: true, length: 255 })
  email: string;

  @Column({ name: 'password_hash', length: 500 })
  password_hash: string;

  @Column({ length: 30, nullable: true })
  phone: string;

  /** Canonical form of `phone` (see toCanonicalPhone); what mobile login looks users up by. */
  @Column({ name: 'phone_key', type: 'varchar', length: 20, nullable: true })
  phone_key: string | null;

  /**
   * Database-enforced "one active user per phone": equals `phone_key` while the user is
   * pending/active and NULL otherwise, with a unique index. Generated by MySQL, never written by the app.
   */
  @Index('UQ_users_active_phone_key', { unique: true })
  @Column({
    name: 'active_phone_key',
    type: 'varchar',
    length: 20,
    nullable: true,
    insert: false,
    update: false,
    asExpression: "CASE WHEN `status` IN ('active','pending') THEN `phone_key` ELSE NULL END",
    generatedType: 'STORED',
  })
  active_phone_key: string | null;

  /** Legacy group id, kept so migrated data retains its team structure (D11). No rules attached yet. */
  @Column({ name: 'team_id', type: 'int', nullable: true })
  team_id: number | null;

  /** Bumped on logout / password change; tokens carry the value they were issued with. */
  @Column({ name: 'token_version', type: 'int', default: 0 })
  token_version: number;

  /** Set for imported/admin-created accounts with a temporary password; cleared when the user sets their own. */
  @Column({ name: 'must_change_password', type: 'boolean', default: false })
  must_change_password: boolean;

  @Column({ length: 500, nullable: true })
  address: string;

  @Column({ name: 'social_links', type: 'json', nullable: true })
  social_links: Record<string, string>;

  @Column({ name: 'company_id', nullable: true })
  company_id: string;

  @Column({ name: 'platform_role', length: 100, nullable: true })
  platform_role: string;

  @Column({
    type: 'enum',
    enum: UserStatus,
    default: UserStatus.PENDING,
  })
  status: UserStatus;

  @Column({ name: 'whatsapp_phone', length: 30, nullable: true })
  whatsapp_phone: string;

  @OneToMany(() => CompanyMembership, (m) => m.user)
  memberships: CompanyMembership[];

  @BeforeInsert()
  @BeforeUpdate()
  syncPhoneKey() {
    // Only when the phone is part of this save; repo.update() callers set phone_key themselves.
    if (this.phone !== undefined) this.phone_key = this.phone ? toCanonicalPhone(this.phone) : null;
  }

  @CreateDateColumn({ name: 'created_at' })
  created_at: Date;

  @UpdateDateColumn({ name: 'updated_at' })
  updated_at: Date;
}
